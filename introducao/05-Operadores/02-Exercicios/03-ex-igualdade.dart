//Operadores relacionais de comparação

void main(){

  //Dois valores para comparar entre si
  final int valor1 = 10;
  final int valor2 = 2;

  // ==  verifica a igualdade != verifica a diferença

  print('valor1 == valor2: ${valor1 == valor2}');//false
  print('valor1 =! valor2 ${valor1 != valor2}');//false
  print('valor1 > valor2: ${valor1 > valor2}');
  print('valor1 < valor2: ${valor1 < valor2}');
}